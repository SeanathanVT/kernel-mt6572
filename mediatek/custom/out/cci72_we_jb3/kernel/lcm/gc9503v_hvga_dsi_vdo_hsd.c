static void lcm_set_util_funcs(const LCM_UTIL_FUNCS *util)
{
    memcpy(&lcm_util, util, sizeof(LCM_UTIL_FUNCS));
}

static void lcm_get_params(LCM_PARAMS *params)
{
    memset(params, 0, sizeof(LCM_PARAMS));

    params->type   = LCM_TYPE_DSI;
    params->width  = FRAME_WIDTH;
    params->height = FRAME_HEIGHT;

    params->dsi.mode = SYNC_PULSE_VDO_MODE;
    params->dsi.LANE_NUM = LCM_TWO_LANE;

    params->dsi.data_format.color_order = LCM_COLOR_ORDER_RGB;
    params->dsi.data_format.trans_seq   = LCM_DSI_TRANS_SEQ_MSB_FIRST;
    params->dsi.data_format.padding     = LCM_DSI_PADDING_ON_LSB;
    params->dsi.data_format.format      = LCM_DSI_FORMAT_RGB888;

    params->dsi.intermediat_buffer_num = 2;
    params->dsi.PS = LCM_PACKED_PS_24BIT_RGB888;

    params->dsi.word_count  = FRAME_WIDTH * 3;
    params->dsi.packet_size = 256;

    params->dsi.vertical_sync_active  = 8;
    params->dsi.vertical_backporch    = 60;
    params->dsi.vertical_frontporch   = 60;
    params->dsi.vertical_active_line  = FRAME_HEIGHT;

    params->dsi.horizontal_sync_active  = 10;
    params->dsi.horizontal_backporch    = 200;
    params->dsi.horizontal_frontporch   = 200;
    params->dsi.horizontal_active_pixel = FRAME_WIDTH;

    // PLL config (stock values; fref=26MHz, fvco=fref*(fbk_div+1)*2/div)
    params->dsi.pll_div1 = 1;
    params->dsi.pll_div2 = 0;
    params->dsi.fbk_div  = 13;
}

static void lcm_init(void)
{
    SET_RESET_PIN(1);
    MDELAY(10);
    SET_RESET_PIN(0);
    MDELAY(10);
    SET_RESET_PIN(1);
    MDELAY(120);

    push_table(lcm_initialization_setting,
               sizeof(lcm_initialization_setting) / sizeof(struct LCM_setting_table), 1);
}

static void lcm_suspend(void)
{
    push_table(lcm_deep_sleep_mode_in_setting,
               sizeof(lcm_deep_sleep_mode_in_setting) / sizeof(struct LCM_setting_table), 1);
}

static void lcm_resume(void)
{
    lcm_init();
}

// Read DA register 0x04 (3 bytes); GC9503V reports id (buf[1]<<8 | buf[2]) == 0x9503.
static unsigned int lcm_compare_id(void)
{
    unsigned int id;
    unsigned char buffer[3];
    unsigned int data_array[16];

    SET_RESET_PIN(1);
    MDELAY(10);
    SET_RESET_PIN(0);
    MDELAY(10);
    SET_RESET_PIN(1);
    MDELAY(120);

    data_array[0] = 0x00033700;   // set max return packet size = 3
    dsi_set_cmdq(data_array, 1, 1);

    read_reg_v2(0x04, buffer, 3);
    id = ((unsigned int)buffer[1] << 8) | buffer[2];

    return (id == 0x9503) ? 1 : 0;
}

