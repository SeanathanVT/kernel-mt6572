// GC9503V 480x360 MIPI-DSI video-mode panel (HSD), as used on the Innioasis Y1
// (MTK project g368_nyx).  The Y1's panel is auto-detected at boot between this
// and st7701_hvga_dsi_vdo_boe via compare_id, exactly as the stock LK does.
//
// The init sequence, DSI timing, reset timing and compare_id below were
// recovered byte-for-byte from the device's own stock lk.bin (the g368_nyx BSP
// is not public, and this panel is not in the cci72_we_jb3 GPL drop, which
// ships only nt35510_dsi_cmd_6572 -- the wrong controller/mode, which hangs
// display init and watchdog-resets the kernel).

